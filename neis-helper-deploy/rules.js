    let m = blockText.match(/성\s*명\s*[:：]?\s*([가-힣]{2,5})/);
    if (m && !FIELD_LABELS.has(m[1])) return m[1];
    // 라벨이었다면 값 행에서 다시 찾는다. **그 줄이 정말 라벨 행일 때만** 그렇게 한다 —
    // 같은 줄에 다른 항목 라벨이 함께 있어야 라벨 행이다. 조건 없이 다음 줄을 보면
